#!/usr/bin/env python3
"""Refresh nginx Cloudflare real-IP ranges atomically and fail closed on bad input."""
from __future__ import annotations

import argparse
import datetime
import ipaddress
import os
import pathlib
import subprocess
import tempfile
import urllib.request

SOURCES = (
    ("v4", "https://www.cloudflare.com/ips-v4"),
    ("v6", "https://www.cloudflare.com/ips-v6"),
)


def parse_ranges(values, version):
    networks = []
    for raw in values:
        value = raw.strip()
        if not value:
            continue
        network = ipaddress.ip_network(value, strict=True)
        if network.version != version:
            raise ValueError(f"expected IPv{version}: {value}")
        networks.append(str(network))
    if len(set(networks)) < 5:
        raise ValueError(f"too few IPv{version} ranges")
    return sorted(set(networks), key=lambda value: (ipaddress.ip_network(value).network_address, ipaddress.ip_network(value).prefixlen))


def render(v4, v6):
    stamp = datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat()
    lines = [
        "# Generated by tools/sync_cloudflare_realip.py; do not edit by hand.",
        f"# Source: official Cloudflare ips-v4 / ips-v6; fetched {stamp}.",
        "real_ip_header CF-Connecting-IP;",
        "real_ip_recursive on;",
        "",
    ]
    lines.extend(f"set_real_ip_from {value};" for value in v4 + v6)
    lines.extend(("", "# Reject direct-to-origin requests; /.well-known/ has a local exception.",))
    lines.extend(f"allow {value};" for value in v4 + v6)
    lines.extend(("allow 127.0.0.1;", "allow ::1;", "deny all;", ""))
    return "\n".join(lines)


def read_sources(directory):
    values = {}
    for name, url in SOURCES:
        if directory:
            values[name] = pathlib.Path(directory, f"ips-{name}").read_text(encoding="utf-8").splitlines()
            continue
        request = urllib.request.Request(url, headers={"User-Agent": "JubeatViewer-CloudflareRangeSync/1.0"})
        with urllib.request.urlopen(request, timeout=20) as response:
            raw = response.read(256 * 1024 + 1)
        if len(raw) > 256 * 1024:
            raise ValueError(f"oversized source: {url}")
        values[name] = raw.decode("utf-8").splitlines()
    return values


def atomic_write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix="." + path.name + ".", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    finally:
        pathlib.Path(temporary).unlink(missing_ok=True)


def sync(conf, source_dir=None, nginx=None, reload=False):
    conf = pathlib.Path(conf)
    if conf.is_symlink():
        raise ValueError("refusing a symlink configuration")
    values = read_sources(source_dir)
    data = render(parse_ranges(values["v4"], 4), parse_ranges(values["v6"], 6))
    previous = conf.read_bytes() if conf.is_file() else None
    atomic_write(conf, data)
    try:
        if nginx:
            subprocess.run([nginx, "-t"], check=True, capture_output=True)
            if reload:
                subprocess.run([nginx, "-s", "reload"], check=True, capture_output=True)
    except BaseException:
        if previous is None:
            conf.unlink(missing_ok=True)
        else:
            atomic_write(conf, previous.decode("utf-8"))
        raise
    return {"v4": len(parse_ranges(values["v4"], 4)), "v6": len(parse_ranges(values["v6"], 6)), "bytes": len(data.encode())}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--conf", required=True, type=pathlib.Path)
    parser.add_argument("--source-dir", type=pathlib.Path, help="test-only directory containing ips-v4 and ips-v6")
    parser.add_argument("--nginx", help="nginx binary; runs -t before optional reload")
    parser.add_argument("--reload", action="store_true")
    args = parser.parse_args()
    result = sync(args.conf, args.source_dir, args.nginx, args.reload)
    print(f"Cloudflare ranges: {result['v4']} IPv4, {result['v6']} IPv6, {result['bytes']} bytes")


if __name__ == "__main__":
    main()
